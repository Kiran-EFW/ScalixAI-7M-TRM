"""
Text dataset for multimodal training with Gemini-generated data
"""

import os
import json
from typing import Tuple, List, Dict, Optional, Any
import numpy as np
import torch
from torch.utils.data import IterableDataset, get_worker_info
import pydantic
from transformers import AutoTokenizer

from dataset.common import PuzzleDatasetMetadata
from models.losses import IGNORE_LABEL_ID

class TextDatasetConfig(pydantic.BaseModel):
    seed: int
    dataset_paths: List[str]
    global_batch_size: int
    test_set_mode: bool
    epochs_per_iter: int
    rank: int
    num_replicas: int
    max_seq_len: int = 2048
    tokenizer_name: str = "microsoft/DialoGPT-small"  # Can be changed to other tokenizers
    modalities: List[str] = ["coding", "reasoning", "agentic_browsing", "conversation"]

class TextDataset(IterableDataset):
    """Dataset for text-based training data generated by Gemini API"""

    def __init__(self, config: TextDatasetConfig, split: str = "train"):
        super().__init__()
        self.config = config
        self.split = split

        # Initialize tokenizer
        self.tokenizer = AutoTokenizer.from_pretrained(config.tokenizer_name)
        if self.tokenizer.pad_token is None:
            self.tokenizer.pad_token = self.tokenizer.eos_token

        # Load and process data
        self.examples = []
        self.modality_counts = {}

        for dataset_path in config.dataset_paths:
            self._load_dataset(dataset_path)

        # Calculate metadata
        self.metadata = self._create_metadata()

        # Set up data structures for batching
        self.rng = np.random.Generator(np.random.PCG64(config.seed + config.rank))

        # Group examples by modality for balanced sampling
        self.modality_groups = {}
        for modality in config.modalities:
            self.modality_groups[modality] = [
                i for i, ex in enumerate(self.examples)
                if ex.get("modality") == modality
            ]

    def _load_dataset(self, dataset_path: str):
        """Load dataset from JSON file"""
        if not os.path.exists(dataset_path):
            raise FileNotFoundError(f"Dataset file not found: {dataset_path}")

        with open(dataset_path, 'r', encoding='utf-8') as f:
            data = json.load(f)

        if isinstance(data, list):
            self.examples.extend(data)
        else:
            # Handle single example
            self.examples.append(data)

    def _create_metadata(self) -> PuzzleDatasetMetadata:
        """Create metadata compatible with the existing training pipeline"""
        # Calculate statistics
        total_examples = len(self.examples)
        vocab_size = self.tokenizer.vocab_size

        # Count modalities
        for example in self.examples:
            modality = example.get("modality", "unknown")
            self.modality_counts[modality] = self.modality_counts.get(modality, 0) + 1

        # Create dummy puzzle identifiers (one per modality)
        num_puzzle_identifiers = len(self.config.modalities)

        return PuzzleDatasetMetadata(
            seq_len=self.config.max_seq_len,
            vocab_size=vocab_size,
            pad_id=self.tokenizer.pad_token_id,
            ignore_label_id=IGNORE_LABEL_ID,
            blank_identifier_id=0,  # Not used for text
            num_puzzle_identifiers=num_puzzle_identifiers,
            sets=["train", "test"],  # Simplified
            total_puzzles=num_puzzle_identifiers,
            total_groups=num_puzzle_identifiers,
            mean_puzzle_examples=total_examples // num_puzzle_identifiers if num_puzzle_identifiers > 0 else total_examples,
            total_examples=total_examples
        )

    def _tokenize_example(self, example: Dict[str, Any]) -> Dict[str, torch.Tensor]:
        """Tokenize a single example"""
        input_text = example["input"]
        output_text = example["output"]

        # Combine input and output for sequence-to-sequence style training
        full_text = f"Input: {input_text}\nOutput: {output_text}"

        # Tokenize
        tokens = self.tokenizer(
            full_text,
            max_length=self.config.max_seq_len,
            padding='max_length',
            truncation=True,
            return_tensors='pt'
        )

        # Create labels (same as input for language modeling, but shifted for generation)
        labels = tokens['input_ids'].clone()
        labels[labels == self.tokenizer.pad_token_id] = IGNORE_LABEL_ID

        return {
            'input_ids': tokens['input_ids'].squeeze(),
            'attention_mask': tokens['attention_mask'].squeeze(),
            'labels': labels.squeeze(),
            'modality': example.get('modality', 'unknown')
        }

    def __iter__(self):
        """Iterate over the dataset"""
        worker_info = get_worker_info()
        if worker_info is not None:
            # Split workload across workers
            num_workers = worker_info.num_workers
            worker_id = worker_info.id

            # Simple split: each worker gets a portion of examples
            examples_per_worker = len(self.examples) // num_workers
            start_idx = worker_id * examples_per_worker
            end_idx = start_idx + examples_per_worker if worker_id < num_workers - 1 else len(self.examples)
            worker_examples = self.examples[start_idx:end_idx]
        else:
            worker_examples = self.examples

        # Shuffle examples
        indices = list(range(len(worker_examples)))
        self.rng.shuffle(indices)

        for idx in indices:
            example = worker_examples[idx]
            tokenized = self._tokenize_example(example)

            # Convert to batch format expected by training loop
            batch = {
                'input_ids': tokenized['input_ids'],
                'attention_mask': tokenized['attention_mask'],
                'labels': tokenized['labels'],
                'modality': tokenized['modality']
            }

            # Add puzzle identifier based on modality
            modality_idx = self.config.modalities.index(tokenized['modality']) if tokenized['modality'] in self.config.modalities else 0
            batch['puzzle_identifier'] = torch.tensor(modality_idx, dtype=torch.long)

            yield batch

class MultimodalDataset(IterableDataset):
    """Combined dataset that can handle both puzzle and text data"""

    def __init__(self, config: Dict[str, Any], split: str = "train"):
        super().__init__()
        self.config = config
        self.split = split

        # Determine dataset types from paths
        self.puzzle_paths = []
        self.text_paths = []

        for path in config['dataset_paths']:
            if path.endswith('.json') and not any(x in path for x in ['arc', 'sudoku', 'maze']):
                self.text_paths.append(path)
            else:
                self.puzzle_paths.append(path)

        # Initialize datasets
        self.puzzle_dataset = None
        self.text_dataset = None

        if self.puzzle_paths:
            from puzzle_dataset import PuzzleDataset, PuzzleDatasetConfig
            puzzle_config = PuzzleDatasetConfig(**config)
            self.puzzle_dataset = PuzzleDataset(puzzle_config, split)

        if self.text_paths:
            text_config = TextDatasetConfig(**config)
            self.text_dataset = TextDataset(text_config, split)

        # Merge metadata
        self.metadata = self._merge_metadata()

    def _merge_metadata(self) -> PuzzleDatasetMetadata:
        """Merge metadata from different dataset types"""
        if self.puzzle_dataset and self.text_dataset:
            # Combine metadata - use puzzle dataset as base and extend
            base_metadata = self.puzzle_dataset.metadata

            return PuzzleDatasetMetadata(
                seq_len=max(base_metadata.seq_len, self.text_dataset.metadata.seq_len),
                vocab_size=max(base_metadata.vocab_size, self.text_dataset.metadata.vocab_size),
                pad_id=base_metadata.pad_id,  # Keep puzzle pad_id as primary
                ignore_label_id=base_metadata.ignore_label_id,
                blank_identifier_id=base_metadata.blank_identifier_id,
                num_puzzle_identifiers=base_metadata.num_puzzle_identifiers + self.text_dataset.metadata.num_puzzle_identifiers,
                sets=list(set(base_metadata.sets + self.text_dataset.metadata.sets)),
                total_puzzles=base_metadata.total_puzzles + self.text_dataset.metadata.total_puzzles,
                total_groups=base_metadata.total_groups + self.text_dataset.metadata.total_groups,
                mean_puzzle_examples=(base_metadata.mean_puzzle_examples + self.text_dataset.metadata.mean_puzzle_examples) / 2,
                total_examples=getattr(base_metadata, 'total_examples', 0) + self.text_dataset.metadata.total_examples
            )
        elif self.puzzle_dataset:
            return self.puzzle_dataset.metadata
        elif self.text_dataset:
            return self.text_dataset.metadata
        else:
            raise ValueError("No datasets loaded")

    def __iter__(self):
        """Iterate over combined datasets"""
        # Alternate between puzzle and text data for balanced training
        puzzle_iter = iter(self.puzzle_dataset) if self.puzzle_dataset else None
        text_iter = iter(self.text_dataset) if self.text_dataset else None

        puzzle_done = puzzle_iter is None
        text_done = text_iter is None

        while not (puzzle_done and text_done):
            # Alternate between datasets
            if not puzzle_done:
                try:
                    yield next(puzzle_iter)
                except StopIteration:
                    puzzle_done = True

            if not text_done:
                try:
                    yield next(text_iter)
                except StopIteration:
                    text_done = True

def create_multimodal_dataloader(config: Dict[str, Any], split: str, rank: int, world_size: int, **kwargs):
    """Create dataloader for multimodal training"""
    dataset = MultimodalDataset(config, split=split)
    dataloader = torch.utils.data.DataLoader(
        dataset,
        batch_size=None,  # Dataset handles batching
        num_workers=1,
        prefetch_factor=8,
        pin_memory=True,
        persistent_workers=True
    )
    return dataloader, dataset.metadata
